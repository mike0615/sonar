"""Export scan results to CSV, TXT, HTML and XML."""

from __future__ import annotations

import csv
import html
import io
import time
from typing import List, Sequence
from xml.etree import ElementTree as ET

from . import APP_NAME, __version__
from .scanner import HostResult

COLUMNS = [
    ("ip", "IP Address"),
    ("rtt", "Response"),
    ("hostname", "Host Name"),
    ("mac", "MAC Address"),
    ("vendor", "Vendor"),
    ("netbios", "NetBIOS Name"),
    ("workgroup", "Workgroup"),
    ("open_ports", "Open Ports"),
    ("status", "Status"),
]

FORMATS = {"csv": "CSV (*.csv)", "txt": "Text (*.txt)", "html": "HTML (*.html)", "xml": "XML (*.xml)"}


def row(r: HostResult) -> List[str]:
    return [r.ip, r.rtt_text(), r.hostname, r.mac, r.vendor, r.netbios, r.workgroup,
            r.ports_text(), "up" if r.alive else "no response"]


def to_csv(results: Sequence[HostResult]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([c[1] for c in COLUMNS])
    for r in results:
        w.writerow(row(r))
    return buf.getvalue()


def to_txt(results: Sequence[HostResult]) -> str:
    rows = [[c[1] for c in COLUMNS]] + [row(r) for r in results]
    widths = [max(len(x[i]) for x in rows) for i in range(len(COLUMNS))]
    lines = ["%s %s scan results - %s" % (APP_NAME, __version__, time.strftime("%Y-%m-%d %H:%M:%S")), ""]
    for n, cells in enumerate(rows):
        lines.append("  ".join(c.ljust(widths[i]) for i, c in enumerate(cells)).rstrip())
        if n == 0:
            lines.append("  ".join("-" * w for w in widths))
    lines.append("")
    lines.append("%d host(s)" % len(results))
    return "\n".join(lines) + "\n"


def to_html(results: Sequence[HostResult]) -> str:
    e = html.escape
    out = ["<!DOCTYPE html>", "<html><head><meta charset='utf-8'>",
           "<title>%s scan results</title>" % e(APP_NAME),
           "<style>body{font-family:sans-serif}table{border-collapse:collapse}"
           "th,td{border:1px solid #bbb;padding:3px 8px;text-align:left}"
           "th{background:#0b3a5b;color:#fff}tr:nth-child(even){background:#eef4f8}</style>",
           "</head><body>",
           "<h2>%s scan results</h2><p>%s &middot; %d host(s)</p>"
           % (e(APP_NAME), e(time.strftime("%Y-%m-%d %H:%M:%S")), len(results)),
           "<table><tr>" + "".join("<th>%s</th>" % e(c[1]) for c in COLUMNS) + "</tr>"]
    for r in results:
        out.append("<tr>" + "".join("<td>%s</td>" % e(c) for c in row(r)) + "</tr>")
    out.append("</table><p><small>Generated by %s %s</small></p></body></html>" % (e(APP_NAME), e(__version__)))
    return "\n".join(out) + "\n"


def to_xml(results: Sequence[HostResult]) -> str:
    root = ET.Element("sonar", version=__version__, generated=time.strftime("%Y-%m-%dT%H:%M:%S"))
    for r in results:
        h = ET.SubElement(root, "host", ip=r.ip, status="up" if r.alive else "down")
        for key, val in (("response_ms", "" if r.rtt_ms is None else "%.1f" % r.rtt_ms),
                         ("hostname", r.hostname), ("mac", r.mac), ("vendor", r.vendor),
                         ("netbios", r.netbios), ("workgroup", r.workgroup)):
            if val:
                ET.SubElement(h, key).text = val
        if r.open_ports:
            ports = ET.SubElement(h, "ports")
            for p in r.open_ports:
                ET.SubElement(ports, "port", number=str(p), protocol="tcp", state="open")
    _indent(root)
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"


def _indent(elem, level=0):
    pad = "\n" + "  " * level
    if len(elem):
        if not (elem.text or "").strip():
            elem.text = pad + "  "
        for child in elem:
            _indent(child, level + 1)
        if not (child.tail or "").strip():
            child.tail = pad
    if level and not (elem.tail or "").strip():
        elem.tail = pad


WRITERS = {"csv": to_csv, "txt": to_txt, "html": to_html, "xml": to_xml}


def export(results: Sequence[HostResult], path: str, fmt: str = "") -> str:
    fmt = (fmt or path.rsplit(".", 1)[-1]).lower()
    if fmt == "htm":
        fmt = "html"
    if fmt not in WRITERS:
        raise ValueError("Unknown export format: %s" % fmt)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(WRITERS[fmt](results))
    return fmt
